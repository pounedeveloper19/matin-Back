-- ستون TariffId جدول Bills الزامی (NOT NULL) بود و باعث می‌شد
-- ثبت سفارش مشتری با پیام «تعرفه‌ای برای این اشتراک یافت نشد»
-- رد شود، حتی وقتی مشتری قرارداد فعال دارد — چون تعرفه (Tariff)
-- فقط برای بعضی شرکت‌های برق دستی ثبت شده (دقیقاً مثل باگ قبلی TOU).
-- بررسی کد نشان داد Bill.TariffId هیچ‌جا برای محاسبه استفاده
-- نمی‌شود (فقط موقع ثبت ذخیره می‌شود)، پس این ستون nullable می‌شود
-- تا نبودِ تعرفه دیگر جلوی ثبت سفارش را نگیرد.
-- ============================================================

ALTER TABLE dbo.Bills ALTER COLUMN TariffId INT NULL;
