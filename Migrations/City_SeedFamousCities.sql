INSERT INTO dbo.City (ProvinceId, Title)
SELECT p.Id, r.CityTitle
FROM @rows r
JOIN dbo.Provinces p ON p.Name LIKE r.ProvincePattern
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.City c WHERE c.ProvinceId = p.Id AND c.Title = r.CityTitle
);

SELECT COUNT(*) AS CitiesInserted FROM dbo.City;
